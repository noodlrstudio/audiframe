import { writeFileSync } from "node:fs";
import {
  OPERATIONS,
  bootstrapSchemas,
  envelopeSchema,
  manifestSchema,
  snapshotSchema,
} from "../packages/protocol/dist/index.js";
const save = (name, schema) =>
  writeFileSync(
    `spec/schemas/${name}.json`,
    JSON.stringify(
      {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        $id: `https://audiframe.org/spec/1.0/${name}.json`,
        ...schema,
      },
      null,
      2,
    ) + "\n",
  );
save("envelope", envelopeSchema);
save("manifest", manifestSchema);
save("snapshot", snapshotSchema);
for (const [type, schema] of Object.entries(bootstrapSchemas))
  save(type.replace("/", "-"), schema);
for (const [type, op] of Object.entries(OPERATIONS)) {
  save(type.replace("/", "-") + "-input", op.input);
  if (op.output) save(type.replace("/", "-") + "-output", op.output);
}
function tsType(schema) {
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((x) => JSON.stringify(x)).join(" | ");
  if (schema.oneOf) return schema.oneOf.map(tsType).join(" | ");
  if (schema.type === "string") return "string";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "null") return "null";
  if (schema.type === "array") return `Array<${tsType(schema.items ?? {})}>`;
  if (schema.type === "object")
    return schema.properties
      ? `{ ${Object.entries(schema.properties)
          .map(
            ([key, value]) =>
              `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${tsType(value)}`,
          )
          .join("; ")} }`
      : "Record<string, Json>";
  return "Json";
}
writeFileSync(
  "packages/protocol/src/generated.ts",
  `// Generated by scripts/schemas.mjs. Do not hand edit.\nimport type { Json } from './types';\nexport interface OperationInputs {\n${Object.entries(
    OPERATIONS,
  )
    .map(([type, op]) => `  ${JSON.stringify(type)}: ${tsType(op.input)};`)
    .join("\n")}\n}\nexport interface OperationOutputs {\n${Object.entries(
    OPERATIONS,
  )
    .filter(([, op]) => op.output)
    .map(([type, op]) => `  ${JSON.stringify(type)}: ${tsType(op.output)};`)
    .join("\n")}\n}\nexport type RequestOperation = keyof OperationOutputs;\n`,
);
